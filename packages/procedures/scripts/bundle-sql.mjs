#!/usr/bin/env node
/**
 * Reads all SQL files from gtfs/ and generates:
 *   dist/sql-bundle.js  — JS Map for the web app's bundled loader
 *   dist/gtfs.sql       — standalone SQL file for DuckDB CLI
 */
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sqlDir = path.join(root, "gtfs");
const outDir = path.join(root, "dist");

async function collectSqlFiles(dir, prefix = "") {
  const entries = await readdir(dir, { withFileTypes: true });
  const results = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const relPath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      results.push(...(await collectSqlFiles(fullPath, relPath)));
    } else if (entry.name.endsWith(".sql")) {
      const key = relPath.replace(/\.sql$/, "");
      const content = await readFile(fullPath, "utf8");
      results.push({ key, content });
    }
  }
  return results;
}

const files = await collectSqlFiles(sqlDir);

// ── JS bundle (Map for web app) ──────────────────────────────────────────────

const entries = files
  .map(
    (f) =>
      `  [${JSON.stringify(f.key)}, ${JSON.stringify(f.content)}]`
  )
  .join(",\n");

const jsContent = `// Auto-generated by scripts/bundle-sql.mjs — do not edit
export const SQL_BUNDLE = new Map([
${entries}
]);
`;

const dtsContent = `// Auto-generated by scripts/bundle-sql.mjs — do not edit
export declare const SQL_BUNDLE: Map<string, string>;
`;

// ── Standalone gtfs.sql (concatenated, for DuckDB CLI) ───────────────────────

// Installation order: enums → edit tables → views → materialized tables →
// pathway network → query macros → pathfinding
const installOrder = [
  "utils/gtfs_enums",
  "tables/create_edit_stop_table",
  "tables/create_edit_pathway_table",
  "tables/create_stops_view",
  "tables/create_pathways_view",
  "tables/create_station_views",
  "tables/create_stops_table",
  "tables/create_stations_table",
  "tables/initialize_pathway_network",
  "queries/get_station_info",
  "queries/get_station_stops",
  "queries/get_station_pathways",
  "queries/get_pathway_aggregates",
  "queries/get_pathways_filtered",
  "queries/get_time_interval_ranges",
  "queries/get_station_routes",
  "pathfinding/find_shortest_path",
  "pathfinding/find_reachable_stops",
  "pathfinding/find_all_paths",
  "pathfinding/get_direct_pathways",
  "pathfinding/get_station_routes",
];

const sqlByKey = new Map(files.map((f) => [f.key, f.content]));
const sqlParts = [
  "-- ============================================================================",
  "-- GTFS Extension for DuckDB",
  "-- ============================================================================",
  "-- Auto-generated by scripts/bundle-sql.mjs — do not edit",
  "-- Load with:  .read gtfs.sql",
  "-- ============================================================================\n",
];

for (const key of installOrder) {
  const content = sqlByKey.get(key);
  if (content) {
    sqlParts.push(`-- ${key}\n${content.trim()}\n`);
  }
}

sqlParts.push("\nSELECT 'GTFS extension installed' AS status;\n");

// Add the full install SQL to the bundle so web can access it
const gtfsSqlContent = sqlParts.join("\n");
files.push({ key: "__install__", content: gtfsSqlContent });

// Regenerate JS bundle with __install__ included
const allEntries = files
  .map(
    (f) =>
      `  [${JSON.stringify(f.key)}, ${JSON.stringify(f.content)}]`
  )
  .join(",\n");

const jsContentFinal = `// Auto-generated by scripts/bundle-sql.mjs — do not edit
export const SQL_BUNDLE = new Map([
${allEntries}
]);
`;

// ── Write outputs ────────────────────────────────────────────────────────────

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, "sql-bundle.js"), jsContentFinal);
await writeFile(path.join(outDir, "sql-bundle.d.ts"), dtsContent);
await writeFile(path.join(outDir, "gtfs.sql"), gtfsSqlContent);

// Also write to gtfs/ so it's committed to the repo and accessible via GitHub raw URL
await writeFile(path.join(sqlDir, "gtfs.sql"), gtfsSqlContent);

console.log(`Bundled ${files.length} SQL files into dist/sql-bundle.js`);
console.log(`Built standalone gtfs/gtfs.sql + dist/gtfs.sql (${installOrder.length} procedures)`);
